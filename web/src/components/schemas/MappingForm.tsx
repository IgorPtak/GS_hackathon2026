import type { ConfigValidationError, SchemaProfile, SchemaProfileProposal } from "../../api/types";
import { FieldErrors } from "./FieldErrors";
import { FieldMappingRow } from "./FieldMappingRow";
import { FingerprintPicker } from "./FingerprintPicker";
import { MatchConditionsEditor } from "./MatchConditionsEditor";
import {
  errorsUnder,
  FIELD_NAMES,
  fromSpec,
  isValidProfileId,
  toSpec,
  type FieldName,
} from "./schemaDraft";

interface MappingFormProps {
  readonly profile: SchemaProfile;
  readonly paths: readonly string[];
  readonly origin: Pick<SchemaProfileProposal, "generated_by" | "model" | "notes">;
  readonly errors: readonly ConfigValidationError[];
  readonly onChange: (profile: SchemaProfile) => void;
}

/** Editable schema profile, prefilled from a proposal. */
export function MappingForm({ profile, paths, origin, errors, onChange }: MappingFormProps) {
  const isIdValid = isValidProfileId(profile.id);
  const inputClass = "w-full rounded border border-slate-300 px-2 py-1 text-sm";

  function setField(name: FieldName, spec: Parameters<typeof fromSpec>[0]) {
    onChange({ ...profile, fields: { ...profile.fields, [name]: fromSpec(spec) } });
  }

  return (
    <div className="space-y-3">
      <p className="text-xs">
        <span className="rounded bg-slate-200 px-2 py-0.5">
          generated by {origin.generated_by}
          {origin.model ? ` (${origin.model})` : ""}
        </span>
      </p>
      {origin.notes && origin.notes.length > 0 ? (
        <details className="rounded bg-sky-50 px-3 py-2 text-xs text-sky-900">
          <summary className="cursor-pointer font-medium">
            Hints from the proposal ({origin.notes.length})
          </summary>
          <ul className="mt-1 list-disc space-y-0.5 pl-4">
            {origin.notes.map((note, i) => (
              <li key={i} className="break-words">
                {note}
              </li>
            ))}
          </ul>
        </details>
      ) : null}
      <div className="grid gap-2 sm:grid-cols-[1fr_6rem]">
        <div>
          <label htmlFor="profile-id" className="text-sm font-medium">
            Profile id
          </label>
          <input
            id="profile-id"
            value={profile.id}
            onChange={(e) => {
              onChange({ ...profile, id: e.target.value });
            }}
            aria-invalid={!isIdValid}
            className={`${inputClass} font-mono`}
          />
          {!isIdValid ? (
            <p className="text-xs text-red-700">
              Use lowercase letters, digits and single dashes (e.g. payments-declined).
            </p>
          ) : null}
          <FieldErrors errors={errorsUnder(errors, "id")} />
        </div>
        <div>
          <label htmlFor="profile-priority" className="text-sm font-medium">
            Priority
          </label>
          <input
            id="profile-priority"
            type="number"
            value={profile.priority}
            onChange={(e) => {
              onChange({ ...profile, priority: Number(e.target.value) });
            }}
            className={inputClass}
          />
          <FieldErrors errors={errorsUnder(errors, "priority")} />
        </div>
      </div>
      <div>
        <label htmlFor="profile-description" className="text-sm font-medium">
          Description
        </label>
        <input
          id="profile-description"
          value={profile.description}
          onChange={(e) => {
            onChange({ ...profile, description: e.target.value });
          }}
          className={inputClass}
        />
        <FieldErrors errors={errorsUnder(errors, "description")} />
      </div>
      <MatchConditionsEditor
        match={profile.match}
        paths={paths}
        errors={errorsUnder(errors, "match")}
        onChange={(match) => {
          onChange({ ...profile, match });
        }}
      />
      <div className="space-y-2">
        <h4 className="text-sm font-medium">Normalized fields</h4>
        {FIELD_NAMES.map((name) => (
          <FieldMappingRow
            key={name}
            name={name}
            spec={toSpec(profile.fields[name])}
            paths={paths}
            errors={errorsUnder(errors, `fields.${name}`)}
            onChange={(spec) => {
              setField(name, spec);
            }}
          />
        ))}
      </div>
      <FingerprintPicker
        selected={profile.fingerprint}
        paths={paths}
        errors={errorsUnder(errors, "fingerprint")}
        onChange={(fingerprint) => {
          onChange({ ...profile, fingerprint });
        }}
      />
    </div>
  );
}
